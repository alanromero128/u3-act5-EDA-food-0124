import pandas as pd
import matplotlib.pyplot as plt 
# Alan Romero  NC 0124
# 1. Leer el archivo CSV comida pais India 
print("\n--- DATOS LEIDOS DESDE CSV,comida india 0124")
df_food_india= pd.read_csv('indian_food.csv')
print(df_food_india)
print("\n--- Mostrar Nombre comida + ingredientes 0124")
recipes = df_food_india[['name', 'ingredients']]
print(recipes)
print("\n--- Tiempo de cocinado mostrar 10 registrar con head 0124 ---")
nombre_y_hora = df_food_india[['name', 'cook_time']].head(10)
print(nombre_y_hora)
print("\n--- Grafica comida (X) Tiempo de cocinado (Y)---")
print("\n--- Grafica comida (X) texto a 30 grados ---")
nombre_y_hora.plot.bar(x="name", y="cook_time", rot=30)
plt.title("Comida tipica de india Alan 0124")
plt.xlabel("Nombre del platllo")
plt.ylabel("tiempo cocinando")
plt.show()
plt.title('Grafica de vaias columnas Alan 0124')
nombre_y_hora= df_food_india[['name', 'prep_time', 'cook_time']].head(10)
nombre_y_hora.plot.bar(x='name', rot=30)
plt.title("Grafica de 2 columnas Alan 0124")
plt.xlabel("Nombre del platllo")
plt.ylabel("tiempo de cocinado prep y comida")
plt.show()
print("\n--- Graficas apiladas una tras otra verticalmente 0124")
nombre_y_hora.plot.bar(x='name',stacked=True,rot=30)
plt.title(" Graficas apiladas Alan 0124")
plt.xlabel("Nombre del platllo")
plt.ylabel("tiempo de cocinado prep y comida")
plt.show()
